import os


def system_language():
    value = (os.environ.get('LC_ALL') or os.environ.get('LANGUAGE', '').split(':')[0]
             or os.environ.get('LC_MESSAGES') or os.environ.get('LANG') or 'en')
    return 'es' if value.lower().replace('-', '_').split('_')[0].split('.')[0] == 'es' else 'en'


_language = system_language()


def set_language(language):
    global _language
    _language = language if language in ('es', 'en') else system_language()


def get_language():
    return _language


